  // Word-aware wrapping keeps translated labels within the finalized Chinese geometry.
  function wrapLabel(value, width, size) {
    const measure = label => Array.from(label).reduce((total, char) => total + size * (
      /[MW@%]/u.test(char) ? .9 : /[A-ZÀ-ÖØ-Þ]/u.test(char) ? .68 :
      /[ilI.,:;!'’ ]/u.test(char) ? .29 : /[frt]/u.test(char) ? .4 : .56
    ), 0) * 1.05;
    const rows = []; let row = '';
    for (const word of String(value).split(/\s+/u)) {
      const next = row ? `${row} ${word}` : word;
      if (row && measure(next) > width) { rows.push(row); row = word; }
      else row = next;
    }
    if (row) rows.push(row);
    return rows;
  }

  function fittedLines(x, y, value, width, options = {}, maxLines = 2) {
    let size = options.size || 14, rows = wrapLabel(value, width, size);
    while (rows.length > maxLines && size > 10) {
      size = Math.round((size - .2) * 10) / 10;
      rows = wrapLabel(value, width, size);
    }
    return lines(x, y, rows, {...options, size, leading: options.leading || size * 1.25});
  }

